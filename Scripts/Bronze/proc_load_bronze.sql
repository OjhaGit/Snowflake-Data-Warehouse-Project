-- =====================================================
-- BRONZE LAYER: LOAD STORED PROCEDURE
-- =====================================================

CREATE OR REPLACE PROCEDURE DATAWAREHOUSE.BRONZE.LOAD_BRONZE()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$

DECLARE
    START_TIME        TIMESTAMP_NTZ;
    END_TIME          TIMESTAMP_NTZ;
    BATCH_START_TIME  TIMESTAMP_NTZ;
    BATCH_END_TIME    TIMESTAMP_NTZ;

BEGIN

    BATCH_START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ==============================================
    -- START BRONZE LOADING
    -- ==============================================

    -- ==============================================
    -- LOADING CRM TABLES
    -- ==============================================

    -- 1. CRM CUSTOMER INFO
    START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    TRUNCATE TABLE DATAWAREHOUSE.BRONZE.CRM_CUST_INFO;

    COPY INTO DATAWAREHOUSE.BRONZE.CRM_CUST_INFO
    FROM @DATAWAREHOUSE.BRONZE.CRM_STG_FILES/cust_info.csv
    FILE_FORMAT = (FORMAT_NAME = 'DATAWAREHOUSE.BRONZE.CRM')
    ON_ERROR = 'ABORT_STATEMENT'
    FORCE = TRUE;

    END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- 2. CRM PRODUCT INFO
    START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    TRUNCATE TABLE DATAWAREHOUSE.BRONZE.CRM_PRD_INFO;

    COPY INTO DATAWAREHOUSE.BRONZE.CRM_PRD_INFO
    FROM @DATAWAREHOUSE.BRONZE.CRM_STG_FILES/prd_info.csv
    FILE_FORMAT = (FORMAT_NAME = 'DATAWAREHOUSE.BRONZE.CRM')
    ON_ERROR = 'ABORT_STATEMENT'
    FORCE = TRUE;

    END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- 3. CRM SALES DETAILS
    START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    TRUNCATE TABLE DATAWAREHOUSE.BRONZE.CRM_SALES_DETAILS;

    COPY INTO DATAWAREHOUSE.BRONZE.CRM_SALES_DETAILS
    FROM @DATAWAREHOUSE.BRONZE.CRM_STG_FILES/sales_details.csv
    FILE_FORMAT = (FORMAT_NAME = 'DATAWAREHOUSE.BRONZE.CRM')
    ON_ERROR = 'ABORT_STATEMENT'
    FORCE = TRUE;

    END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ==============================================
    -- LOADING ERP TABLES
    -- ==============================================

    -- 4. ERP CUSTOMER
    START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    TRUNCATE TABLE DATAWAREHOUSE.BRONZE.ERP_CUST_AZ12;

    COPY INTO DATAWAREHOUSE.BRONZE.ERP_CUST_AZ12
    FROM @DATAWAREHOUSE.BRONZE.ERP_STG_FILES/CUST_AZ12.csv
    FILE_FORMAT = (FORMAT_NAME = 'DATAWAREHOUSE.BRONZE.ERP')
    ON_ERROR = 'ABORT_STATEMENT'
    FORCE = TRUE;

    END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- 5. ERP LOCATION
    START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    TRUNCATE TABLE DATAWAREHOUSE.BRONZE.ERP_LOC_A101;

    COPY INTO DATAWAREHOUSE.BRONZE.ERP_LOC_A101
    FROM @DATAWAREHOUSE.BRONZE.ERP_STG_FILES/LOC_A101.csv
    FILE_FORMAT = (FORMAT_NAME = 'DATAWAREHOUSE.BRONZE.ERP')
    ON_ERROR = 'ABORT_STATEMENT'
    FORCE = TRUE;

    END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- 6. ERP PRODUCT CATEGORY
    START_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    TRUNCATE TABLE DATAWAREHOUSE.BRONZE.ERP_PX_CAT_G1V2;

    COPY INTO DATAWAREHOUSE.BRONZE.ERP_PX_CAT_G1V2
    FROM @DATAWAREHOUSE.BRONZE.ERP_STG_FILES/PX_CAT_G1V2.csv
    FILE_FORMAT = (FORMAT_NAME = 'DATAWAREHOUSE.BRONZE.ERP')
    ON_ERROR = 'ABORT_STATEMENT'
    FORCE = TRUE;

    END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ==============================================
    -- BATCH COMPLETION
    -- ==============================================

    BATCH_END_TIME := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    RETURN
        '========================================='
        || CHAR(10) || 'BRONZE LAYER LOADING COMPLETED'
        || CHAR(10) || 'Total Load Duration: '
        || DATEDIFF(SECOND, BATCH_START_TIME, BATCH_END_TIME)
        || ' seconds'
        || CHAR(10) || '=========================================';

EXCEPTION
    WHEN OTHER THEN
        RETURN
            'BRONZE LAYER LOADING FAILED'
            || CHAR(10) || 'Error Code: ' || SQLCODE
            || CHAR(10) || 'Error Message: ' || SQLERRM
            || CHAR(10) || 'SQL State: ' || SQLSTATE;

END;
$$;
CALL DATAWAREHOUSE.BRONZE.LOAD_BRONZE();

